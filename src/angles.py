"""Angle — 무엇을 강조할 것인가.

외부 검토에서 나온 핵심 지적: 기존 페르소나 10종에 Tone / Lens / Format 이 뒤섞여
있었다. pro=말투, careful=관점, brief=구조 를 한 축에 둔 것이 실제 문제였다.

축을 셋으로 분해한다.
    Voice  (말투)   ×  Angle (강조점)  ×  Format (구조)

Angle 은 미리 정해두지 않는다. 정해두면 데이터에 없는 관점을 억지로 쓰다가
환각이 난다. 대신 **입력 사실관계가 실제로 허용하는 각도만 추출**해서
그중 하나를 고르게 한다.

예) 공시에 "계약금액 1,200억 / 매출 대비 18% / 기간 3년" 이 있으면
      scale(매출 대비 18%), amount(1,200억), duration(3년), uncertainty(이행조건 미공개)
    이 후보로 잡히고, 이번 글은 그중 하나만 강조한다.
    같은 공시라도 강조점이 달라지면 완전히 다른 글이 된다.
"""
import re

# (id, 표시명, 탐지 정규식, 작성 지시)
ANGLES = [
    ("ratio", "비중·비율",
     r"\d+(\.\d+)?\s*%|대비\s*\d|비율",
     "비율·비중 숫자 하나를 글의 축으로 삼는다. 절대 금액보다 '무엇 대비 얼마인지'를 앞세운다."),

    ("amount", "규모",
     r"\d[\d,]*\s*(억원|조원|원)|발행 총액|조달",
     "금액이나 수량의 크기를 축으로 삼는다. 다른 수치는 곁가지로만 언급한다."),

    ("duration", "기간·시점",
     r"만기|기간|\d{4}[-년]\s*\d{1,2}|예정일|시행|적용",
     "언제부터 언제까지인지, 시점이 갖는 의미를 축으로 삼는다."),

    ("terms", "조건",
     r"전환가액|행사가액|이자율|배정|취득 방법|합병 비율|증자 방식",
     "발행·거래 조건을 축으로 삼는다. 조건이 무엇을 뜻하는지 짧게 풀어 쓴다."),

    ("reaction", "시장 반응",
     r"등락률|거래대금|종가",
     "가격과 거래 규모라는 관찰된 반응을 축으로 삼는다. 원인을 단정하지 않는다."),

    ("purpose", "목적·용도",
     r"자금|용도|목적|시설자금|운영자금|채무상환",
     "돈을 어디에 쓰는지, 무엇을 하려는지를 축으로 삼는다."),

    ("context", "업황·배경",
     r"\[검색으로 확인된 배경\]|주력|사업|업종",
     "회사가 무엇을 하는 곳인지, 어떤 업황에 있는지를 축으로 삼는다. "
     "사실관계에 없는 과거 사례나 수치를 끌어오지 않는다."),

    ("uncertainty", "미확인 지점",
     r"미제공|명시되지 않|공개되지 않|확인되지 않|추정하지",
     "아직 확인되지 않은 지점 하나를 축으로 삼는다. "
     "다만 '정보가 없다'는 말로 글을 채우지 말고, "
     "왜 그 지점이 중요한지를 한 문장으로 설명한다."),
]

_MAP = {a[0]: a for a in ANGLES}


def available(item: dict) -> list[str]:
    """이 항목의 사실관계가 실제로 허용하는 Angle 목록."""
    facts = item.get("facts", "")
    core = "\n".join(l for l in facts.splitlines()
                     if l.strip() and not l.strip().startswith("※"))
    out = [aid for aid, _, pat, _ in ANGLES if re.search(pat, core)]

    # uncertainty 단독은 글이 되지 않는다.
    # '정보가 없다'만 남는 글이 반복됐던 원인이라 다른 각도가 있을 때만 후보로 둔다.
    if out == ["uncertainty"]:
        return []
    return out


def desc(angle_id: str) -> str:
    a = _MAP.get(angle_id)
    return a[3] if a else "확인된 사실 중 가장 중요한 하나를 축으로 삼는다."


def name(angle_id: str) -> str:
    a = _MAP.get(angle_id)
    return a[1] if a else "일반"
